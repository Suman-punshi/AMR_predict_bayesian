import json
import numpy as np
import matplotlib.pyplot as plt
import os
from scipy.stats import norm


def plot_comparative_histograms(avg_file, eval_log_files, model_names, specie, output_dir="figures"):
    """
    Plot comparative histograms of model evaluation metrics (AUROC, AUPRC, Balanced Acc, F1 (Weighted))
    for each label across multiple models, formatted to journal half-page figure standards.

    Parameters:
    - avg_file (str): Path to the JSON file with aggregated (mean + std) metrics.
    - eval_log_files (List[str]): List of evaluation log JSON files (per run or model).
    - model_names (List[str]): Names of models corresponding to eval_log_files (first one is average).
    - specie (str): Species name for plot titles.
    - output_dir (str): Directory where plots will be saved.
    """

    os.makedirs(output_dir, exist_ok=True)

    # Load averaged metrics
    with open(avg_file, "r") as f:
        avg_data = json.load(f)

    # Load evaluation logs
    eval_logs = []
    for file in eval_log_files:
        with open(file, "r") as f:
            eval_logs.append(json.load(f))

    # Colors for models
    colors = plt.cm.tab10(np.linspace(0, 1, len(model_names)))

    # Labels (per-class metrics keys, skip mean_metrics)
    labels = [k for k in avg_data.keys() if k != "mean_metrics"]

    # Mapping for short metric labels
    label_map = {
        "BALANCED_ACCURACY": "Balanced Acc",
        "WEIGHTED_F1": "F1 (Weighted)",
        "AUROC": "AUROC",
        "AUPRC": "AUPRC"
    }

    for label in labels:
        metrics = ["AUROC", "AUPRC", "BALANCED_ACCURACY", "WEIGHTED_F1"]
        short_metrics = [label_map[m] for m in metrics]

        means, errors = [], []

        # First model = averaged run (mean + std)
        avg_metrics = avg_data[label]
        model_means = [avg_metrics[m]["mean"] for m in metrics]
        model_stds = [avg_metrics[m]["std"] for m in metrics]
        means.append(model_means)
        errors.append(model_stds)

        # Remaining models (raw logs, no error bars)
        for log in eval_logs:
            per_label_list = [d for d in log["metrics_per_label"] if d["label"].lower() == label.lower()]
            if per_label_list:
                per_label = per_label_list[0]
                model_means = [
                    per_label["auroc"],
                    per_label["auprc"],
                    per_label["balanced_accuracy"],
                    per_label["weighted_f1"]
                ]
            else:
                model_means = [np.nan] * len(metrics)
            means.append(model_means)
            errors.append([0.0] * len(metrics))

        means = np.array(means)
        errors = np.array(errors)

        # === Plotting ===
        x = np.arange(len(metrics))
        width = 0.8 / len(model_names)

        # Half-page figure size: 85 mm (3.35 in) width, ~2.8 in height
        fig, ax = plt.subplots(figsize=(3.35, 2.8), dpi=300)

        for i in range(len(model_names)):
            ax.bar(
                x + i * width - (len(model_names)-1)/2 * width,
                means[i],
                width=width,
                yerr=errors[i] if i == 0 else None,
                capsize=2,
                color=colors[i],
                label=model_names[i]
            )

        # Formatting
        ax.set_title(f"{specie} - {label}", fontsize=9, weight="bold", pad=5)
        ax.set_xticks(x)
        ax.set_xticklabels(short_metrics, rotation=25, ha="right", fontsize=7)
        ax.set_ylabel("Score", fontsize=8)
        ax.set_ylim(0, 1.05)
        ax.yaxis.grid(True, linestyle="--", alpha=0.6)

        # Legend below plot
        ax.legend(
            fontsize=6, frameon=False,
            loc="upper center",
            bbox_to_anchor=(0.5, -0.3),
            ncol=len(model_names)
        )

        # Save (300 dpi ensures print quality at final size)
        fname = os.path.join(output_dir, f"{specie}_{label.replace(' ', '_')}_comparison.png")
        plt.savefig(fname, dpi=300, bbox_inches="tight")
        plt.close()

        print(f"Saved {fname}")



def plot_uncertainty_distributions(log_file, specie, output_dir="uncertainty_plots"):
    """
    Plot Gaussian distributions of TP, TN, FP, FN uncertainties per label
    based on mean and std from a Bayesian evaluation log.

    Parameters:
    - log_file (str): Path to the JSON log file generated by evaluate_multilabel_bayesiansetup.
    - specie (str): Species name for the plots and filenames.
    - output_dir (str): Directory where plots will be saved.
    """

    # Load JSON log
    with open(log_file, "r") as f:
        data = json.load(f)

    labels = data["label_names"]
    metrics = data["metrics_per_label"]

    os.makedirs(output_dir, exist_ok=True)

    # Colors for TP, TN, FP, FN
    color_map = {
        "TP": "green",
        "TN": "blue",
        "FP": "red",
        "FN": "orange"
    }

    for entry in metrics:
        label = entry["label"]
        unc = entry["uncertainty"]

        # Extract means and stds for TP, TN, FP, FN
        groups = {
            "TP": (unc["tp_mean_uncertainty"], unc["tp_std_uncertainty"]),
            "TN": (unc["tn_mean_uncertainty"], unc["tn_std_uncertainty"]),
            "FP": (unc["fp_mean_uncertainty"], unc["fp_std_uncertainty"]),
            "FN": (unc["fn_mean_uncertainty"], unc["fn_std_uncertainty"]),
        }

        # Sort by ascending mean, but push invalid (-1) to the end
        sorted_groups = sorted(groups.items(), key=lambda x: (x[1][0] if x[1][0] != -1 else float("inf")))

        # Define plotting range (exclude invalid ones)
        means = [m for _, (m, s) in sorted_groups if m != -1 and s != -1 and not np.isnan(m)]
        stds = [s for _, (m, s) in sorted_groups if m != -1 and s != -1 and not np.isnan(s)]

        if not means or not stds:
            print(f"Skipping {label}: no valid uncertainty values")
            continue

        xmin = min(means) - 3 * max(stds)
        xmax = max(means) + 3 * max(stds)
        x = np.linspace(xmin, xmax, 500)

        # === Plotting ===
        fig, ax = plt.subplots(figsize=(3.35, 2.5), dpi=300)  # Half-page width, ~85 mm

        for group, (mean, std) in sorted_groups:
            if mean == -1 or std == -1 or np.isnan(mean) or np.isnan(std) or std == 0:
                # Add dummy entry for legend
                ax.plot([], [], label=f"{group} (NaN)", color=color_map[group], linestyle="--")
                continue

            y = norm.pdf(x, mean, std)
            ax.plot(x, y, label=group, color=color_map[group], linewidth=1.5)

        # Formatting
        ax.set_title(f"{specie} - {label}", fontsize=10, weight="bold")
        ax.set_xlabel("Uncertainty", fontsize=9)
        ax.set_ylabel("Density", fontsize=9)
        ax.legend(frameon=False, fontsize=7, loc="upper right")
        ax.grid(True, linestyle="--", alpha=0.6)

        # Save with specie + antibiotic in filename
        fname = os.path.join(output_dir, f"{specie}_{label.replace(' ', '_')}_uncertainty.png")
        plt.savefig(fname, dpi=300, bbox_inches="tight")
        plt.close()
        print(f"Saved {fname}")





